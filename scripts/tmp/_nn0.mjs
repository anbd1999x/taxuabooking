import { PrismaClient } from "@prisma/client";
const p = new PrismaClient();
const n = (x) => (x ?? "").normalize("NFD").replace(/\p{M}/gu, "").replace(/đ/gi, "d").toLowerCase();
const re = /soc|nau/;
const s = await p.service.findMany({ select: { title: true, slug: true, category: true, contactName: true } });
console.log("services", s.length, s.filter((x) => re.test(n(x.title) + x.slug + n(x.contactName))));
const rt = await p.roomType.findMany({ select: { name: true, service: { select: { title: true } } } });
console.log(rt.filter((x) => re.test(n(x.name))).map((x) => x.service.title + " / " + x.name));
const r = await p.room.findMany({ select: { name: true, roomType: { select: { service: { select: { title: true } } } } } });
console.log(r.filter((x) => re.test(n(x.name))).map((x) => x.roomType.service.title + " / " + x.name));
